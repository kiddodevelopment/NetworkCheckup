// Package report renders a snapshot as Markdown.
package report

import (
	"fmt"
	"strings"

	"netcheckup/engine"
)

var badge = map[engine.Status]string{
	engine.Good: "🟢 OK", engine.Warn: "🟡 Check", engine.Bad: "🔴 Problem", engine.Info: "🔵 Info", engine.Limited: "⚪ Limited",
}

func esc(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(s, "\n", " ")
}

// Markdown renders the whole snapshot.
func Markdown(s engine.Snapshot) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# Network Checkup report\n\n")
	w("- **Computer:** %s (%s/%s)\n", s.Hostname, s.OS, s.Arch)
	w("- **Taken:** %s\n", s.Started.Format("2006-01-02 15:04:05 MST"))
	w("- **Duration:** %.1f s\n", s.Finished.Sub(s.Started).Seconds())
	w("- **Tool version:** %s\n\n", s.Version)

	w("## Summary: %s\n\n", badge[s.Overall])
	w("| Check | Status | Result |\n| --- | --- | --- |\n")
	for _, r := range s.Results {
		w("| %s | %s | %s |\n", esc(r.Title), badge[r.Status], esc(r.Summary))
	}
	w("\n")

	var issues []string
	for _, r := range s.Results {
		for _, f := range r.Findings {
			if f.Status == engine.Bad || f.Status == engine.Warn {
				issues = append(issues, fmt.Sprintf("- %s **%s** (%s): %s", badge[f.Status], f.Title, r.Title, f.Explain))
			}
		}
	}
	w("## Flagged issues\n\n")
	if len(issues) == 0 {
		w("None.\n\n")
	} else {
		w("%s\n\n", strings.Join(issues, "\n"))
	}

	section := ""
	for _, r := range s.Results {
		if r.Section != section {
			section = r.Section
			w("## %s\n\n", section)
		}
		w("### %s %s\n\n%s\n\n", badge[r.Status], r.Title, r.Summary)
		for _, f := range r.Findings {
			w("- %s **%s**: %s\n", badge[f.Status], f.Title, f.Explain)
		}
		if len(r.Findings) > 0 {
			w("\n")
		}
		if len(r.Details) > 0 {
			w("| Detail | Value |\n| --- | --- |\n")
			for _, d := range r.Details {
				w("| %s | %s |\n", esc(d.Key), esc(d.Value))
			}
			w("\n")
		}
		for _, t := range r.Tables {
			if len(t.Rows) == 0 {
				continue
			}
			w("**%s**\n\n| %s |\n|%s\n", t.Title, strings.Join(t.Columns, " | "), strings.Repeat(" --- |", len(t.Columns)))
			for _, row := range t.Rows {
				cells := make([]string, len(row))
				for i, c := range row {
					cells[i] = esc(c)
				}
				w("| %s |\n", strings.Join(cells, " | "))
			}
			w("\n")
		}
		for _, l := range r.Limits {
			w("> Limited: %s\n", l)
		}
		if len(r.Limits) > 0 {
			w("\n")
		}
	}
	w("---\nGenerated by Network Checkup. No logins were attempted and nothing was sent anywhere.\n")
	return b.String()
}
