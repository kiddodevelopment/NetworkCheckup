//! Renders a snapshot as Markdown.

use crate::engine::{Snapshot, Status};
use std::fmt::Write;

pub fn badge(s: Status) -> &'static str {
    match s {
        Status::Good => "🟢 OK",
        Status::Warn => "🟡 Check",
        Status::Bad => "🔴 Problem",
        Status::Info => "🔵 Info",
        Status::Limited => "⚪ Limited",
    }
}

fn esc(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

pub fn markdown(s: &Snapshot) -> String {
    let mut b = String::new();
    let started = chrono::DateTime::parse_from_rfc3339(&s.started).ok();
    let finished = chrono::DateTime::parse_from_rfc3339(&s.finished).ok();
    let _ = writeln!(b, "# Network Checkup report\n");
    let _ = writeln!(b, "- **Computer:** {} ({}/{})", s.hostname, s.os, s.arch);
    if let Some(t) = started {
        let _ = writeln!(b, "- **Taken:** {}", t.format("%Y-%m-%d %H:%M:%S %:z"));
    }
    if let (Some(a), Some(z)) = (started, finished) {
        let _ = writeln!(b, "- **Duration:** {:.1} s", (z - a).num_milliseconds() as f64 / 1000.0);
    }
    let _ = writeln!(b, "- **Tool version:** {}\n", s.version);

    let _ = writeln!(b, "## Summary: {}\n", badge(s.overall));
    b.push_str("| Check | Status | Result |\n| --- | --- | --- |\n");
    for r in &s.results {
        let _ = writeln!(b, "| {} | {} | {} |", esc(&r.title), badge(r.status), esc(&r.summary));
    }
    b.push('\n');

    let issues: Vec<String> = s
        .results
        .iter()
        .flat_map(|r| {
            r.findings
                .iter()
                .filter(|f| matches!(f.status, Status::Bad | Status::Warn))
                .map(move |f| format!("- {} **{}** ({}): {}", badge(f.status), f.title, r.title, f.explain))
        })
        .collect();
    b.push_str("## Flagged issues\n\n");
    if issues.is_empty() {
        b.push_str("None.\n\n");
    } else {
        let _ = write!(b, "{}\n\n", issues.join("\n"));
    }

    let mut section = "";
    for r in &s.results {
        if r.section != section {
            section = &r.section;
            let _ = writeln!(b, "## {section}\n");
        }
        let _ = write!(b, "### {} {}\n\n{}\n\n", badge(r.status), r.title, r.summary);
        for f in &r.findings {
            let _ = writeln!(b, "- {} **{}**: {}", badge(f.status), f.title, f.explain);
        }
        if !r.findings.is_empty() {
            b.push('\n');
        }
        if !r.details.is_empty() {
            b.push_str("| Detail | Value |\n| --- | --- |\n");
            for d in &r.details {
                let _ = writeln!(b, "| {} | {} |", esc(&d.key), esc(&d.value));
            }
            b.push('\n');
        }
        for t in &r.tables {
            if t.rows.is_empty() {
                continue;
            }
            let _ = write!(b, "**{}**\n\n| {} |\n|{}\n", t.title, t.columns.join(" | "), " --- |".repeat(t.columns.len()));
            for row in &t.rows {
                let cells: Vec<String> = row.iter().map(|c| esc(c)).collect();
                let _ = writeln!(b, "| {} |", cells.join(" | "));
            }
            b.push('\n');
        }
        for l in &r.limits {
            let _ = writeln!(b, "> Limited: {l}");
        }
        if !r.limits.is_empty() {
            b.push('\n');
        }
    }
    b.push_str("---\nGenerated by Network Checkup. No logins were attempted and nothing was sent anywhere.\n");
    b
}
